package org.globalart.astrum.repository.alpine.internal.apk;

import java.io.ByteArrayInputStream;
import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.security.MessageDigest;
import java.util.Arrays;
import java.util.Base64;
import java.util.LinkedHashMap;
import java.util.Map;
import java.util.Map.Entry;

import org.apache.commons.compress.archivers.tar.TarArchiveEntry;
import org.apache.commons.compress.archivers.tar.TarArchiveOutputStream;
import org.junit.Test;

import static org.junit.Assert.assertEquals;
import static org.junit.Assert.assertThrows;

public class ApkPackageParserTest
{
  static final String PKGINFO = "# Generated by abuild 3.13.0-r3\n"
      + "pkgname = zlib\n"
      + "pkgver = 1.3.2-r0\n"
      + "pkgdesc = A compression/decompression Library\n"
      + "url = https://zlib.net/\n"
      + "builddate = 1776180385\n"
      + "packager = Buildozer <alpine-devel@lists.alpinelinux.org>\n"
      + "size = 114688\n"
      + "arch = x86_64\n"
      + "origin = zlib\n"
      + "commit = c859479f9fdc87bd0ad38270d1fd332477304599\n"
      + "maintainer = Natanael Copa <ncopa@alpinelinux.org>\n"
      + "license = Zlib\n"
      + "# automatically detected:\n"
      + "provides = so:libz.so.1=1.3.2\n"
      + "depend = so:libc.musl-x86_64.so.1\n"
      + "datahash = 0e3986122d7ace1173a7d68a0f0c157b9e548b88e63d94df948c7a7ffc2be7f2\n";

  @Test
  public void parsesSignedPackage() throws Exception {
    byte[] control = GzipMembers.gzip(tar(Map.of(".PKGINFO", PKGINFO.getBytes(StandardCharsets.UTF_8)), false));
    byte[] apk = concat(
        GzipMembers.gzip(tar(Map.of(".SIGN.RSA.test.rsa.pub", new byte[256]), false)),
        control,
        GzipMembers.gzip(tar(Map.of("usr/lib/libz.so.1", new byte[1000]), true)));

    ApkPackage apkPackage = ApkPackageParser.parse(new ByteArrayInputStream(apk), apk.length);

    String checksum = "Q1" + Base64.getEncoder().encodeToString(MessageDigest.getInstance("SHA-1").digest(control));
    assertEquals("zlib-1.3.2-r0.apk", apkPackage.fileName());
    assertEquals("C:" + checksum + "\n"
        + "P:zlib\n"
        + "V:1.3.2-r0\n"
        + "A:x86_64\n"
        + "S:" + apk.length + "\n"
        + "I:114688\n"
        + "T:A compression/decompression Library\n"
        + "U:https://zlib.net/\n"
        + "L:Zlib\n"
        + "o:zlib\n"
        + "m:Natanael Copa <ncopa@alpinelinux.org>\n"
        + "t:1776180385\n"
        + "c:c859479f9fdc87bd0ad38270d1fd332477304599\n"
        + "D:so:libc.musl-x86_64.so.1\n"
        + "p:so:libz.so.1=1.3.2\n", apkPackage.indexEntry().text());
  }

  @Test
  public void parsesUnsignedPackage() throws Exception {
    byte[] control = GzipMembers.gzip(tar(Map.of(".PKGINFO", PKGINFO.getBytes(StandardCharsets.UTF_8)), false));
    byte[] apk = concat(control, GzipMembers.gzip(tar(Map.of("file", new byte[10]), true)));

    ApkPackage apkPackage = ApkPackageParser.parse(new ByteArrayInputStream(apk), apk.length);

    assertEquals("zlib", apkPackage.name());
    assertEquals("1.3.2-r0", apkPackage.version());
  }

  @Test
  public void attributesRoundTrip() throws Exception {
    byte[] control = GzipMembers.gzip(tar(Map.of(".PKGINFO", PKGINFO.getBytes(StandardCharsets.UTF_8)), false));
    ApkPackage apkPackage = ApkPackageParser.parse(new ByteArrayInputStream(control), 42);

    assertEquals(apkPackage, ApkPackage.fromAttributes(apkPackage.toAttributes(), 42));
  }

  @Test
  public void rejectsArchivesWithoutPkginfo() throws Exception {
    byte[] apk = GzipMembers.gzip(tar(Map.of("README", new byte[1]), true));
    assertThrows(IOException.class, () -> ApkPackageParser.parse(new ByteArrayInputStream(apk), apk.length));
    byte[] notGzip = "plain text".getBytes(StandardCharsets.UTF_8);
    assertThrows(IOException.class, () -> ApkPackageParser.parse(new ByteArrayInputStream(notGzip), 10));
  }

  static byte[] tar(final Map<String, byte[]> files, final boolean terminate) throws IOException {
    ByteArrayOutputStream out = new ByteArrayOutputStream();
    try (TarArchiveOutputStream tar = new TarArchiveOutputStream(out, 512)) {
      for (Entry<String, byte[]> file : new LinkedHashMap<>(files).entrySet()) {
        TarArchiveEntry entry = new TarArchiveEntry(file.getKey());
        entry.setSize(file.getValue().length);
        tar.putArchiveEntry(entry);
        tar.write(file.getValue());
        tar.closeArchiveEntry();
      }
      tar.finish();
    }
    byte[] bytes = out.toByteArray();
    return terminate ? bytes : Arrays.copyOf(bytes, bytes.length - 1024);
  }

  static byte[] concat(final byte[]... parts) {
    ByteArrayOutputStream out = new ByteArrayOutputStream();
    for (byte[] part : parts) {
      out.writeBytes(part);
    }
    return out.toByteArray();
  }
}
