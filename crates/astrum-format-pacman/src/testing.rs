use std::io::Write;

use crate::archive::Compression;
use crate::paths;

pub struct Spec {
    pub name: String,
    pub version: String,
    pub arch: String,
    pub description: String,
    pub depends: Vec<String>,
    pub provides: Vec<String>,
    pub compression: Compression,
}

impl Spec {
    pub fn new(name: &str, version: &str, arch: &str) -> Spec {
        Spec {
            name: name.to_owned(),
            version: version.to_owned(),
            arch: arch.to_owned(),
            description: format!("{name} for the tests"),
            depends: Vec::new(),
            provides: Vec::new(),
            compression: Compression::Zstd,
        }
    }

    pub fn extension(&self) -> &'static str {
        match self.compression {
            Compression::None => "",
            Compression::Gzip => ".gz",
            Compression::Bzip2 => ".bz2",
            Compression::Xz => ".xz",
            Compression::Zstd => ".zst",
        }
    }

    pub fn file_name(&self) -> String {
        paths::package_file_name(&self.name, &self.version, &self.arch, self.extension())
    }
}

enum Item<'a> {
    Directory(&'a str),
    File(&'a str, &'a [u8]),
}

fn tar(items: &[Item<'_>]) -> Vec<u8> {
    let mut builder = tar::Builder::new(Vec::new());
    for item in items {
        let mut header = tar::Header::new_gnu();
        header.set_uid(0);
        header.set_gid(0);
        header.set_mtime(1_700_000_000);
        match item {
            Item::Directory(name) => {
                header.set_size(0);
                header.set_mode(0o755);
                header.set_entry_type(tar::EntryType::Directory);
                builder
                    .append_data(&mut header, format!("{name}/"), std::io::empty())
                    .expect("the test paths are valid");
            }
            Item::File(name, data) => {
                header.set_size(data.len() as u64);
                header.set_mode(0o644);
                header.set_entry_type(tar::EntryType::Regular);
                builder
                    .append_data(&mut header, name, *data)
                    .expect("the test paths are valid");
            }
        }
    }
    builder
        .into_inner()
        .expect("writing into memory does not fail")
}

pub fn compress(data: &[u8], compression: Compression) -> Vec<u8> {
    match compression {
        Compression::None => data.to_vec(),
        Compression::Gzip => {
            let mut encoder =
                flate2::write::GzEncoder::new(Vec::new(), flate2::Compression::fast());
            encoder
                .write_all(data)
                .expect("writing into memory does not fail");
            encoder.finish().expect("writing into memory does not fail")
        }
        Compression::Bzip2 => {
            let mut encoder = bzip2::write::BzEncoder::new(Vec::new(), bzip2::Compression::fast());
            encoder
                .write_all(data)
                .expect("writing into memory does not fail");
            encoder.finish().expect("writing into memory does not fail")
        }
        Compression::Xz => {
            let mut out = Vec::new();
            lzma_rs::xz_compress(&mut std::io::BufReader::new(data), &mut out)
                .expect("writing into memory does not fail");
            out
        }
        Compression::Zstd => {
            ruzstd::encoding::compress_to_vec(data, ruzstd::encoding::CompressionLevel::Fastest)
        }
    }
}

pub fn tar_zst(files: &[(&str, &[u8])]) -> Vec<u8> {
    let items: Vec<Item<'_>> = files
        .iter()
        .map(|(name, data)| Item::File(name, data))
        .collect();
    compress(&tar(&items), Compression::Zstd)
}

pub fn build(spec: &Spec) -> Vec<u8> {
    let script = format!("#!/bin/sh\necho {} {}\n", spec.name, spec.version);
    let readme = format!("{} {}\n", spec.name, spec.version);
    let mut info = format!(
        "# Generated by makepkg 7.0.0\n# using fakeroot version 1.36\npkgname = {name}\npkgbase = {name}\nxdata = pkgtype=pkg\npkgver = {version}\npkgdesc = {description}\nurl = https://example.org/{name}\nbuilddate = 1700000000\npackager = Astrum Tests <tests@example.org>\nsize = {size}\narch = {arch}\nlicense = MIT\n",
        name = spec.name,
        version = spec.version,
        description = spec.description,
        size = script.len() + readme.len(),
        arch = spec.arch,
    );
    for depend in &spec.depends {
        info.push_str(&format!("depend = {depend}\n"));
    }
    for provide in &spec.provides {
        info.push_str(&format!("provides = {provide}\n"));
    }
    let buildinfo = format!(
        "format = 2\npkgname = {}\npkgver = {}\npkgarch = {}\n",
        spec.name, spec.version, spec.arch
    );
    let mtree = compress(
        b"#mtree\n/set type=file uid=0 gid=0 mode=644\n",
        Compression::Gzip,
    );
    let bin = format!("usr/bin/{}", spec.name);
    let doc = format!("usr/share/doc/{}", spec.name);
    let readme_path = format!("{doc}/README");
    let archive = tar(&[
        Item::File(".BUILDINFO", buildinfo.as_bytes()),
        Item::File(".MTREE", &mtree),
        Item::File(".PKGINFO", info.as_bytes()),
        Item::Directory("usr"),
        Item::Directory("usr/bin"),
        Item::File(&bin, script.as_bytes()),
        Item::Directory("usr/share"),
        Item::Directory("usr/share/doc"),
        Item::Directory(&doc),
        Item::File(&readme_path, readme.as_bytes()),
    ]);
    compress(&archive, spec.compression)
}

pub fn signing_key(passphrase: Option<&str>) -> String {
    use pgp::composed::{ArmorOptions, KeyType, SecretKeyParamsBuilder};
    let mut params = SecretKeyParamsBuilder::default();
    params
        .key_type(KeyType::Ed25519Legacy)
        .can_certify(true)
        .can_sign(true)
        .primary_user_id("Astrum Test <test@example.org>".into());
    if let Some(passphrase) = passphrase {
        params.passphrase(Some(passphrase.to_owned()));
    }
    params
        .build()
        .expect("the test key parameters are valid")
        .generate(rand08::thread_rng())
        .expect("a test key can be generated")
        .to_armored_string(ArmorOptions::default())
        .expect("a test key can be armored")
}

pub fn public_key(armored_secret: &str) -> String {
    use pgp::composed::{ArmorOptions, Deserializable, SignedSecretKey};
    let (key, _) = SignedSecretKey::from_string(armored_secret).expect("the test key is valid");
    key.to_public_key()
        .to_armored_string(ArmorOptions::default())
        .expect("a test key can be armored")
}

pub fn sign(armored_secret: &str, data: &[u8]) -> Vec<u8> {
    crate::signing::SigningKey::read(armored_secret, None)
        .expect("the test key is valid")
        .sign(data)
        .expect("the test key signs")
}

pub fn verify(signature: &[u8], data: &[u8], public_key: &str) -> bool {
    use pgp::composed::{Deserializable, DetachedSignature, SignedPublicKey};
    let Ok((public, _)) = SignedPublicKey::from_string(public_key) else {
        return false;
    };
    let Ok((signature, _)) = DetachedSignature::from_reader_single(signature) else {
        return false;
    };
    signature.verify(&public, data).is_ok()
}
