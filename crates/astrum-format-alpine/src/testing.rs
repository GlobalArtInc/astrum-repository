use std::sync::OnceLock;

use rsa::RsaPrivateKey;
use rsa::pkcs8::EncodePrivateKey;
use sha2::{Digest, Sha256};

use crate::archive;
use crate::signing::SigningKey;

pub struct Spec {
    pub name: String,
    pub version: String,
    pub arch: String,
    pub description: String,
    pub depends: Vec<String>,
    pub provides: Vec<String>,
    pub signed: bool,
}

impl Spec {
    pub fn new(name: &str, version: &str, arch: &str) -> Spec {
        Spec {
            name: name.to_owned(),
            version: version.to_owned(),
            arch: arch.to_owned(),
            description: format!("{name} for the tests"),
            depends: Vec::new(),
            provides: Vec::new(),
            signed: true,
        }
    }
}

pub struct Built {
    pub bytes: Vec<u8>,
    pub control: Vec<u8>,
    pub data: Vec<u8>,
}

pub fn rsa_key() -> RsaPrivateKey {
    static KEY: OnceLock<RsaPrivateKey> = OnceLock::new();
    KEY.get_or_init(|| {
        RsaPrivateKey::new(&mut rand_core06::OsRng, 1024).expect("a test key can be generated")
    })
    .clone()
}

pub fn signing_key() -> String {
    rsa_key()
        .to_pkcs8_pem(Default::default())
        .expect("a test key can be written")
        .to_string()
}

pub fn encrypted_signing_key(passphrase: &str) -> String {
    let der = rsa_key().to_pkcs8_der().expect("a test key can be written");
    crate::pem::encrypt_pkcs8(der.as_bytes(), passphrase, &[7; 16], &[1; 16], 1000)
}

pub fn build(spec: &Spec) -> Built {
    let readme = format!("{} {}\n", spec.name, spec.version);
    let path = format!("usr/share/doc/{}/README", spec.name);
    let data = archive::gzip(
        &archive::tar(&[(path.as_str(), readme.as_bytes())], 1_700_000_000, false)
            .expect("the test paths are valid"),
    );
    let mut info = format!(
        "# Generated by the Astrum tests\npkgname = {}\npkgver = {}\npkgdesc = {}\nurl = https://example.org/{}\nbuilddate = 1700000000\npackager = Astrum Tests <tests@example.org>\nsize = {}\narch = {}\norigin = {}\ncommit = 0123456789abcdef0123456789abcdef01234567\nmaintainer = Astrum Tests <tests@example.org>\nlicense = MIT\n",
        spec.name,
        spec.version,
        spec.description,
        spec.name,
        readme.len(),
        spec.arch,
        spec.name,
    );
    for depend in &spec.depends {
        info.push_str(&format!("depend = {depend}\n"));
    }
    for provide in &spec.provides {
        info.push_str(&format!("provides = {provide}\n"));
    }
    info.push_str(&format!(
        "datahash = {}\n",
        hex::encode(Sha256::digest(&data))
    ));
    let control = archive::gzip(
        &archive::tar(&[(".PKGINFO", info.as_bytes())], 1_700_000_000, true)
            .expect("the control file name is valid"),
    );
    let mut bytes = Vec::new();
    if spec.signed {
        let packager = SigningKey::new(rsa_key(), "packager.rsa.pub".to_owned());
        bytes.extend(packager.signature_member(&control, 1_700_000_000));
    }
    bytes.extend_from_slice(&control);
    bytes.extend_from_slice(&data);
    Built {
        bytes,
        control,
        data,
    }
}

pub fn signature_of(file: &[u8], key_name: &str) -> Option<Vec<u8>> {
    let wanted = format!(".SIGN.RSA.{key_name}");
    let split = archive::split(file, 1 << 30).ok()?;
    split.signatures.iter().find_map(|member| {
        archive::entries(&member.content, |_| true)
            .ok()?
            .into_iter()
            .find(|entry| entry.name == wanted)
            .map(|entry| entry.data)
    })
}

pub fn verify_index(file: &[u8], key_name: &str, public_key: &str) -> bool {
    use rsa::pkcs1v15::{Signature, VerifyingKey};
    use rsa::pkcs8::DecodePublicKey;
    use rsa::signature::Verifier;
    let Some(signature) = signature_of(file, key_name) else {
        return false;
    };
    let Ok(split) = archive::split(file, 1 << 30) else {
        return false;
    };
    let Ok(public) = rsa::RsaPublicKey::from_public_key_pem(public_key) else {
        return false;
    };
    let Ok(signature) = Signature::try_from(signature.as_slice()) else {
        return false;
    };
    VerifyingKey::<sha1::Sha1>::new(public)
        .verify(split.rest, &signature)
        .is_ok()
}

pub fn public_key() -> String {
    crate::pem::public_key(&rsa_key())
}
