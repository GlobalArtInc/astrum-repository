use std::collections::{BTreeMap, BTreeSet, HashSet};

use astrum_blob::{ContentStream, Written};
use astrum_content::store::{self, ComponentKey, PutAsset};
use astrum_content::{Asset, ContentError, Ctx, View};
use astrum_repo::config::{DeployPolicy, WritePolicy};
use serde_json::{Value, json};
use sha2::{Digest, Sha256};

use crate::repodata::{Entry, Generated, MetadataType, MetadataWriter, Repomd};
use crate::rpm::{FileName, Package};
use crate::signing::{self, SigningKey};
use crate::{
    GZIP_TYPE, OTHER, REPODATA, REPOMD, RPM, RPM_TYPE, XML_TYPE, Yum, files, paths, signing::Keys,
};

pub struct Settings {
    pub depth: usize,
    pub strict: bool,
}

pub fn settings(ctx: &Ctx) -> Settings {
    let yum = ctx.repository.attributes.yum.as_ref();
    Settings {
        depth: yum
            .and_then(|yum| yum.repodata_depth)
            .unwrap_or(0)
            .clamp(0, 5) as usize,
        strict: yum.and_then(|yum| yum.deploy_policy) != Some(DeployPolicy::Permissive),
    }
}

pub fn writable(path: &str) -> Result<(), ContentError> {
    match paths::in_repodata(path) {
        true => Err(ContentError::BadRequest(format!(
            "The repodata directories are generated by the repository: {path}"
        ))),
        false => Ok(()),
    }
}

fn check_depth(settings: &Settings, path: &str) -> Result<(), ContentError> {
    if settings.strict && paths::base(path, settings.depth).is_none() {
        return Err(ContentError::BadRequest(format!(
            "RPM packages of this repository must be stored at least {} directories deep, the depth at which its repodata is generated: {path}",
            settings.depth
        )));
    }
    Ok(())
}

pub async fn authorize(ctx: &Ctx, path: &str) -> Result<(), ContentError> {
    let redeploys = ctx
        .repository
        .attributes
        .storage
        .as_ref()
        .and_then(|storage| storage.write_policy)
        .unwrap_or(WritePolicy::Allow)
        == WritePolicy::Allow;
    let exists = store::find(ctx.db(), ctx.name(), path).await?.is_some();
    ctx.require(
        if exists && redeploys {
            View::Edit
        } else {
            View::Add
        },
        path,
    )
}

pub fn component(package: &Package) -> ComponentKey {
    ComponentKey {
        namespace: String::new(),
        name: package.name.clone(),
        version: package.component_version(),
        kind: String::new(),
        attributes: json!({"yum": {"name": package.name}}),
    }
}

pub fn file_component(file: &FileName) -> ComponentKey {
    ComponentKey {
        namespace: String::new(),
        name: file.name.clone(),
        version: file.version_release(),
        kind: String::new(),
        attributes: json!({"yum": {"name": file.name}}),
    }
}

fn rpm_put(ctx: &Ctx, path: &str, package: &Package) -> PutAsset {
    PutAsset::hosted(ctx, path)
        .component(component(package))
        .kind(RPM)
        .content_type(RPM_TYPE)
        .attributes(json!({"yum": package.attributes()}))
}

fn refuse(ctx: &Ctx, written: &Written, error: ContentError) -> ContentError {
    store::discard(ctx.content.clone(), &written.store, written.id.uuid());
    error
}

async fn adopt_rpm(
    ctx: &Ctx,
    written: Written,
    path: Option<&str>,
    directory: &str,
    file_name: Option<&str>,
) -> Result<Asset, ContentError> {
    let package = match files::read_package(ctx, &written.store, written.id, written.size).await {
        Ok(package) => package,
        Err(error) => return Err(refuse(ctx, &written, error)),
    };
    let path = match path {
        Some(path) => path.to_owned(),
        None => {
            let name = file_name
                .map(paths::file_name)
                .filter(|name| paths::is_rpm(name))
                .map(str::to_owned)
                .unwrap_or_else(|| package.file_name());
            match paths::join(directory, &name) {
                Some(path) => path,
                None => {
                    let error =
                        ContentError::BadRequest(format!("{name} is not a valid file name"));
                    return Err(refuse(ctx, &written, error));
                }
            }
        }
    };
    let checks = async {
        writable(&path)?;
        check_depth(&settings(ctx), &path)?;
        authorize(ctx, &path).await
    };
    if let Err(error) = checks.await {
        return Err(refuse(ctx, &written, error));
    }
    store::adopt(ctx, rpm_put(ctx, &path, &package), &written).await
}

pub async fn put(ctx: &Ctx, path: &str, body: ContentStream) -> Result<Asset, ContentError> {
    writable(path)?;
    if paths::is_rpm(path) {
        authorize(ctx, path).await?;
        let written = store::write_blob(ctx, body).await?;
        return adopt_rpm(ctx, written, Some(path), "", None).await;
    }
    if settings(ctx).strict {
        return Err(ContentError::BadRequest(format!(
            "Only RPM packages can be stored in a repository with the strict layout policy: {path}"
        )));
    }
    authorize(ctx, path).await?;
    store::put(ctx, PutAsset::hosted(ctx, path).kind(OTHER), body).await
}

pub fn may_add(ctx: &Ctx) -> Result<(), ContentError> {
    match ctx.grant(View::Add).any() || ctx.grant(View::Edit).any() {
        true => Ok(()),
        false => ctx.require(View::Add, "/"),
    }
}

pub async fn upload(
    ctx: &Ctx,
    directory: &str,
    file_name: Option<&str>,
    body: ContentStream,
) -> Result<Asset, ContentError> {
    let directory = paths::join("", directory)
        .ok_or_else(|| ContentError::BadRequest(format!("{directory} is not a valid directory")))?;
    if paths::in_repodata(&directory) {
        return Err(ContentError::BadRequest(
            "The repodata directories are generated by the repository".to_owned(),
        ));
    }
    may_add(ctx)?;
    let written = store::write_blob(ctx, body).await?;
    adopt_rpm(ctx, written, None, &directory, file_name).await
}

fn fingerprint<'a>(packages: impl IntoIterator<Item = (&'a str, &'a str)>, signer: &str) -> String {
    let mut digest = Sha256::new();
    digest.update(signer.as_bytes());
    for (path, sha256) in packages {
        digest.update(format!("\n{path}\t{sha256}").as_bytes());
    }
    hex::encode(digest.finalize())
}

fn attribute<'a>(found: &'a Asset, key: &str) -> Option<&'a Value> {
    found.attributes.get("yum").and_then(|yum| yum.get(key))
}

fn files_of(found: &Asset) -> Vec<String> {
    attribute(found, "files")
        .and_then(Value::as_array)
        .map(|list| {
            list.iter()
                .filter_map(|file| file.as_str().map(str::to_owned))
                .collect()
        })
        .unwrap_or_default()
}

async fn packages_of(ctx: &Ctx, base: &str, depth: usize) -> Result<Vec<Asset>, ContentError> {
    let found = match base.is_empty() {
        true => files::of_kind(ctx.db(), ctx.name(), RPM).await?,
        false => files::of_kind_under(ctx.db(), ctx.name(), RPM, base).await?,
    };
    Ok(found
        .into_iter()
        .filter(|found| paths::base(&found.path, depth).as_deref() == Some(base))
        .collect())
}

async fn remove_metadata(ctx: &Ctx, base: &str) -> Result<(), ContentError> {
    let directory = paths::repodata_directory(base);
    for kind in [REPOMD, REPODATA] {
        for found in files::of_kind_under(ctx.db(), ctx.name(), kind, &directory).await? {
            if paths::directory(&found.path) == directory {
                store::delete_asset(&ctx.content, found).await?;
            }
        }
    }
    Ok(())
}

async fn remove_unreferenced(
    ctx: &Ctx,
    base: &str,
    keep: &HashSet<String>,
) -> Result<(), ContentError> {
    let directory = paths::repodata_directory(base);
    for found in files::of_kind_under(ctx.db(), ctx.name(), REPODATA, &directory).await? {
        let name = paths::file_name(&found.path);
        if paths::directory(&found.path) != directory || keep.contains(name) {
            continue;
        }
        store::delete_asset(&ctx.content, found).await?;
    }
    Ok(())
}

async fn build(
    ctx: &Ctx,
    base: &str,
    packages: &[Asset],
    timestamp: i64,
) -> Result<(Vec<Generated>, u64, Vec<String>), ContentError> {
    let mut skipped: BTreeSet<String> = BTreeSet::new();
    loop {
        let count = packages.len() - skipped.len();
        let mut writers = Vec::with_capacity(3);
        for kind in MetadataType::ALL {
            writers.push(MetadataWriter::new(kind, count as u64).map_err(ContentError::internal)?);
        }
        let mut failed = false;
        let wanted: Vec<&Asset> = packages
            .iter()
            .filter(|found| !skipped.contains(&found.path))
            .collect();
        for found in wanted {
            let package = match files::read_asset_package(ctx, found).await {
                Ok(package) => package,
                Err(error) => {
                    tracing::warn!(repository = ctx.name(), path = %found.path, %error, "an unreadable package is left out of the repodata");
                    skipped.insert(found.path.clone());
                    failed = true;
                    continue;
                }
            };
            let location = paths::location(base, &found.path);
            let entry = Entry {
                rpm: &package,
                location: &location,
                checksum: &found.sha256,
                size: found.size.max(0) as u64,
                file_time: found.blob_updated_at.timestamp(),
            };
            for writer in writers.iter_mut() {
                writer.package(&entry).map_err(ContentError::internal)?;
            }
        }
        if failed {
            continue;
        }
        let mut generated = Vec::with_capacity(3);
        for writer in writers {
            generated.push(writer.finish(timestamp).map_err(ContentError::internal)?);
        }
        return Ok((generated, count as u64, skipped.into_iter().collect()));
    }
}

pub async fn ensure(
    ctx: &Ctx,
    keys: &Keys,
    base: &str,
    force: bool,
) -> Result<Option<Asset>, ContentError> {
    let settings = settings(ctx);
    let repomd_path = paths::repomd_path(base);
    if paths::depth_of(base) != settings.depth {
        let stale = store::find(ctx.db(), ctx.name(), &repomd_path).await?;
        if stale.is_some() {
            let lock = files::lock(ctx, base).await?;
            remove_metadata(ctx, base).await?;
            lock.commit().await?;
        }
        return Ok(None);
    }
    let key = keys.get(ctx)?;
    let signer = signing::signer(key.as_deref()).to_owned();
    let current = |packages: &[Asset], existing: &Option<Asset>| {
        let print = fingerprint(
            packages
                .iter()
                .map(|found| (found.path.as_str(), found.sha256.as_str())),
            &signer,
        );
        let fresh = existing.as_ref().is_some_and(|found| {
            attribute(found, "fingerprint").and_then(Value::as_str) == Some(print.as_str())
        });
        (print, fresh)
    };
    let packages = packages_of(ctx, base, settings.depth).await?;
    let existing = store::find(ctx.db(), ctx.name(), &repomd_path).await?;
    if packages.is_empty() && !base.is_empty() {
        if existing.is_some() {
            let lock = files::lock(ctx, base).await?;
            remove_metadata(ctx, base).await?;
            lock.commit().await?;
        }
        return Ok(None);
    }
    if !force && current(&packages, &existing).1 {
        return Ok(existing);
    }
    let lock = files::lock(ctx, base).await?;
    let packages = packages_of(ctx, base, settings.depth).await?;
    let existing = store::find(ctx.db(), ctx.name(), &repomd_path).await?;
    let (print, fresh) = current(&packages, &existing);
    if !force && fresh {
        return Ok(existing);
    }
    let stored = rebuild(ctx, key.as_deref(), base, &packages, existing, print).await?;
    lock.commit().await?;
    Ok(Some(stored))
}

async fn rebuild(
    ctx: &Ctx,
    key: Option<&SigningKey>,
    base: &str,
    packages: &[Asset],
    existing: Option<Asset>,
    print: String,
) -> Result<Asset, ContentError> {
    let timestamp = chrono::Utc::now().timestamp();
    let (generated, count, skipped) = build(ctx, base, packages, timestamp).await?;
    let directory = paths::repodata_directory(base);
    let mut names = Vec::with_capacity(generated.len());
    let mut data = Vec::with_capacity(generated.len());
    for file in generated {
        let name = file.file_name().to_owned();
        data.push(file.data.clone());
        files::store_generated(
            ctx,
            &format!("{directory}/{name}"),
            REPODATA,
            GZIP_TYPE,
            file.file,
            json!({}),
        )
        .await?;
        names.push(name);
    }
    let repomd = Repomd {
        revision: Some(timestamp.to_string()),
        data,
    }
    .to_xml();
    let signature_path = paths::signature_path(base);
    let signed = match key {
        Some(key) => {
            let signature = key
                .sign(&repomd)
                .map_err(|error| ContentError::internal(std::io::Error::other(error)))?;
            store::put(
                ctx,
                files::metadata_put(
                    ctx,
                    &signature_path,
                    REPODATA,
                    signing::SIGNATURE_TYPE,
                    json!({}),
                ),
                astrum_blob::content_of(signature),
            )
            .await?;
            true
        }
        None => {
            store::delete(ctx, &signature_path).await?;
            false
        }
    };
    let mut keep: HashSet<String> = names.iter().cloned().collect();
    if let Some(previous) = &existing {
        keep.extend(files_of(previous));
    }
    if signed {
        keep.insert(paths::SIGNATURE.to_owned());
    }
    let attributes = json!({"yum": {
        "fingerprint": print,
        "packageCount": count,
        "files": names,
        "signer": signing::signer(key),
    }});
    let stored = store::put(
        ctx,
        files::metadata_put(ctx, &paths::repomd_path(base), REPOMD, XML_TYPE, attributes),
        astrum_blob::content_of(repomd),
    )
    .await?;
    remove_unreferenced(ctx, base, &keep).await?;
    if !skipped.is_empty() {
        tracing::warn!(
            repository = ctx.name(),
            ?skipped,
            "unreadable packages were left out of the repodata"
        );
    }
    Ok(stored)
}

pub async fn rebuild_all(ctx: &Ctx, keys: &Keys, force: bool) -> Result<u64, ContentError> {
    let settings = settings(ctx);
    let mut bases: BTreeMap<String, ()> = BTreeMap::new();
    for found in files::of_kind(ctx.db(), ctx.name(), RPM).await? {
        if let Some(base) = paths::base(&found.path, settings.depth) {
            bases.insert(base, ());
        }
    }
    if settings.depth == 0 {
        bases.insert(String::new(), ());
    }
    for found in files::of_kind(ctx.db(), ctx.name(), REPOMD).await? {
        if let Some(base) = paths::base_of_metadata(&found.path) {
            bases.insert(base, ());
        }
    }
    let mut rebuilt = 0;
    let mut failure = None;
    for base in bases.keys() {
        match ensure(ctx, keys, base, force).await {
            Ok(Some(_)) => rebuilt += 1,
            Ok(None) => {}
            Err(error) => {
                tracing::warn!(repository = ctx.name(), base = %base, %error, "the repodata was not rebuilt");
                failure = Some(error);
            }
        }
    }
    match failure {
        Some(error) => Err(error),
        None => Ok(rebuilt),
    }
}

pub fn schedule(yum: &Yum, ctx: &Ctx, path: &str) {
    let Some(base) = paths::base(path, settings(ctx).depth) else {
        return;
    };
    let key = format!("{}\n{base}", ctx.name());
    if !yum.pending(&key) {
        return;
    }
    let ctx = ctx.clone();
    let keys = yum.keys.clone();
    let pending = yum.pending.clone();
    tokio::spawn(async move {
        tokio::time::sleep(std::time::Duration::from_millis(500)).await;
        pending
            .lock()
            .expect("the pending rebuild lock is never poisoned")
            .remove(&key);
        if let Err(error) = ensure(&ctx, &keys, &base, false).await {
            tracing::warn!(repository = ctx.name(), base = %base, %error, "the repodata was not rebuilt");
        }
    });
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn fingerprints_follow_paths_checksums_and_the_signer() {
        let a = fingerprint([("/a.rpm", "1")], "unsigned");
        assert_ne!(fingerprint([("/a.rpm", "2")], "unsigned"), a);
        assert_ne!(fingerprint([("/a.rpm", "1")], "abc"), a);
        assert_eq!(fingerprint([("/a.rpm", "1")], "unsigned"), a);
    }
}
